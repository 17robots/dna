#!/usr/bin/env python3
"""Build DNA's native support library, window bridge and language installer.

No bundled graphics or text library is downloaded. Native windowing comes from
Dyn's selected SDK; shaping uses the system FreeType, HarfBuzz and FriBidi
providers. build/deps/static resolves #link("dna_native") to the DNA-owned
archive while ordinary system and window libraries remain shared.
"""
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile

from dyn_path import real_dyn
from runpath import runpath

ROOT = Path(__file__).resolve().parents[1]
DEPS = ROOT / 'build/deps'
HIDE_RUNTIME = '{ local: memcpy; memmove; memset; };\n'
HIDE_RUNTIME_SCRIPT = 'VERSION { ' + HIDE_RUNTIME.strip() + ' }\n'
PACKAGES = ('vterm', 'tree-sitter', 'libpcre2-8', 'libutf8proc')


def run(command, **kwargs):
    subprocess.run([str(part) for part in command], check=True, **kwargs)


def compiler_and_runtime():
    compiler = real_dyn()
    if compiler:
        for directory in (compiler.parent, compiler.parent.parent / 'lib/dyn'):
            if (directory / 'dynrt_shared.o').is_file() and (directory / 'dynrt_support_pic.o').is_file():
                return compiler, directory
    raise SystemExit('Cannot find the Dyn runtime objects (dynrt_shared.o, dynrt_support_pic.o); '
                     'set DYN to the matching dyn executable.')


def hide_runtime():
    DEPS.mkdir(parents=True, exist_ok=True)
    (DEPS / 'hide-runtime.map').write_text(HIDE_RUNTIME)
    return '--version-script=' + str(DEPS / 'hide-runtime.map')


def native_archive(archive, support_object):
    """Keep generated SDK definitions private without changing the shared object."""
    archive = Path(archive)
    with tempfile.TemporaryDirectory(prefix='dna-archive-', dir=archive.parent) as directory:
        work = Path(directory)
        private_object = work / Path(support_object).name
        shutil.copyfile(support_object, private_object)
        defined = subprocess.check_output(
            ['nm', '--defined-only', '-g', '--format=posix', str(private_object)], text=True)
        symbols = sorted({line.split()[0] for line in defined.splitlines()
                          if line.split() and line.split()[0].startswith('dyn_m')})
        if symbols:
            localize = work / 'localize.txt'
            localize.write_text('\n'.join(symbols) + '\n')
            run(['objcopy', '--localize-symbols=' + str(localize), private_object])
        product = work / archive.name
        run(['ar', 'rcs', product, private_object])
        product.replace(archive)


def resolve_library(flag):
    found = subprocess.check_output(['cc', f'-print-file-name=lib{flag[2:]}.so'], text=True).strip()
    if found.startswith('/'):
        return os.path.normpath(found)
    # glibc 2.34+ supplies these in libc itself.
    if flag in ('-lutil', '-ldl', '-lpthread', '-lrt'):
        return None
    raise SystemExit(f'Cannot find the shared library for {flag}.')


def static_script(directory, archive, flags):
    system = []
    for flag in [*flags, '-lutil', '-ldl', '-lpthread', '-lm']:
        if flag.startswith('-l') and flag not in system:
            system.append(flag)
    system = [path for path in map(resolve_library, system) if path]
    directory.mkdir(parents=True, exist_ok=True)
    (directory / 'libdna_native.so').write_text(
        f'/* Generated by scripts/deps.py: DNA native support. */\nGROUP({archive})\n'
        f'INPUT(AS_NEEDED({" ".join(system)}))\n' + HIDE_RUNTIME_SCRIPT)


def terminal_only(compiler, flags, environment):
    staged = DEPS / 'native-dyn-tui'
    if staged.exists():
        shutil.rmtree(staged)
    shutil.copytree(ROOT / 'src/native/dyn', staged)
    shutil.copyfile(ROOT / 'modules/stubs/native_fonts.dyn', staged / 'fonts.dyn')
    (staged / 'memory_text.dyn').unlink()
    shutil.copyfile(ROOT / 'modules/stubs/native_notify_gui.dyn', staged / 'notify_gui.dyn')
    shutil.copyfile(ROOT / 'modules/stubs/native_terminal_gui.dyn', staged / 'terminal_gui.dyn')
    run([sys.executable, ROOT / 'scripts/compile.py', compiler, 'build', staged,
         '--shared', '--release', '--emit-object', '--output', DEPS / 'dna-support-tui.so'], env=environment)
    archive = DEPS / 'install/lib/libdna_native_tui.a'
    native_archive(archive, DEPS / 'dna-support-tui.so.o')
    static_script(DEPS / 'tui-static', archive, flags)


def window_bridge(compiler):
    """Install the SDK Wayland bridge where direct Dyn builds resolve #link."""
    from sdk_check import window_builder
    builder = window_builder(compiler)
    destination = DEPS / 'install/lib/libdyn_window.so'
    temporary = destination.with_name('libdyn_window.tmp.so')
    run([sys.executable, builder, '--output', temporary],
        env=dict(os.environ, CC=os.environ.get('CC', 'cc') + ' -Wl,-soname,libdyn_window.so'))
    temporary.replace(destination)


def main():
    if sys.platform == 'darwin':
        from native_macos import dependencies
        dependencies()
        return
    if not sys.platform.startswith('linux'):
        raise SystemExit('Native dependency builds support Linux and macOS; Windows services remain unfinished.')
    required = ('vterm', 'tree-sitter >= 0.25', 'libpcre2-8', 'libutf8proc')
    if subprocess.run(['pkg-config', '--exists', *required]).returncode:
        raise SystemExit('Install libvterm, Tree-sitter >= 0.25, PCRE2 and utf8proc development packages.')
    compiler, runtime = compiler_and_runtime()
    (DEPS / 'install/lib').mkdir(parents=True, exist_ok=True)
    environment = dict(os.environ, DYN_LIBRARY_PATH=str(DEPS / 'install/lib'))
    flags = shlex.split(subprocess.check_output(['pkg-config', '--libs', *PACKAGES], text=True))
    run([sys.executable, ROOT / 'tests/native_abi.py'], env=environment)
    run([sys.executable, ROOT / 'scripts/compile.py', compiler, 'build', ROOT / 'src/native/dyn',
         '--shared', '--release', '--emit-object', '--output', DEPS / 'dna-support.so'], env=environment)
    objects = [DEPS / 'dna-support.so.o', runtime / 'dynrt_shared.o', runtime / 'dynrt_support_pic.o']
    destination = DEPS / 'install/lib/libdna_native.so'
    temporary = destination.with_name(destination.name + '.tmp')
    run(['cc', '-shared', '-Wl,-soname,libdna_native.so', '-Wl,' + hide_runtime(),
         '-Wl,-z,defs', '-Wl,-rpath,$ORIGIN', *objects, '-lutil', '-pthread', '-ldl',
         '-o', temporary, *flags])
    temporary.replace(destination)
    archive = DEPS / 'install/lib/libdna_native.a'
    native_archive(archive, objects[0])
    static_script(DEPS / 'static', archive, flags)
    terminal_only(compiler, flags, environment)
    window_bridge(compiler)
    (DEPS / 'install/bin').mkdir(parents=True, exist_ok=True)
    (DEPS / 'install/share/dna').mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / 'languages/registry.toml', DEPS / 'install/share/dna/languages.toml')
    shutil.copytree(ROOT / 'languages/queries', DEPS / 'install/share/dna/queries', dirs_exist_ok=True)
    run([sys.executable, ROOT / 'scripts/compile.py', compiler, 'build', ROOT / 'installer',
         '--debug', '--output', DEPS / 'install/bin/dna-language', '--link', destination,
         '--link', runpath(), '--link', hide_runtime()], env=environment)
    print('Built native support, terminal archive, window bridge and language installer.')


if __name__ == '__main__':
    main()
